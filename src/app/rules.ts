export interface RuleExample {
  /** 한자 표기 */
  word: string
  /** 그 표기의 읽기 */
  reading: string
  /** 이 예시가 무엇을 보여주는지 한 줄 */
  note: string
  /** 코퍼스에 없는 단어 (개념 설명용). 기본은 코퍼스 안 */
  outside?: boolean
  /**
   * 이 예시는 절의 규칙이 **분해에 안 잡힌다**. 값은 그 이유 (2026-09-17).
   *
   * 두 가지가 여기 온다 — 규칙이 정말 안 걸린 반례(半分)와, 사전이 결과형을 이미 별도
   * 읽기로 등재해 앱이 그 규칙으로 분류하지 못하는 것(反応). 둘 다 **앱이 이 예시를 이 절로
   * 보내지 않는다**는 뜻이라, 본문이 그렇게 약속하면 거짓말이 된다.
   * `rules.test.ts` 가 분해 결과와 이 표시를 전수로 맞춘다.
   */
  offRule?: string
}

/** 규칙이 걸린 것과 안 걸린 것을 나란히 — 경계를 배우는 자리다 (context-notes 2026-09-07) */
export interface RuleContrast {
  applied: RuleExample
  blocked: RuleExample
  /** 무엇이 둘을 갈랐나 */
  because: string
}

export interface RuleSection {
  id: RuleId
  title: string
  /** 목록에서 보이는 한 줄 */
  summary: string
  /** 본문 문단 */
  body: string[]
  examples: RuleExample[]
  contrasts: RuleContrast[]
  /** 이 절이 다루는 오답 유형. 기록 색인이 이 유형들로 모은다 */
  mistakes: MistakeType[]
  /**
   * RENDAKU 바구니 안에서 이 절이 맡는 갈래 (2026-09-17).
   * 분류기는 연탁·반탁·연성을 한 유형으로 묶으므로 세 절이 같은 유형을 나눠 갖는다 —
   * 어느 절로 보낼지는 `explainMistake` 의 `voicing` 이 정한다
   */
  voicing?: VoicingKind
}

